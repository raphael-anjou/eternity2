"""Frame-aware first-moment bulge of the official 16x16, for scan orders and seams.

Run: python3 -I bulge16.py <path to engine/data/official_eternity2.csv>
"""
import sys
from collections import Counter
from math import log10, comb

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from model import (interior_match_logp, frame_match_logp, profile, logsum10,
                   cell_kind, log10_fact)

N = 16


def load(fn):
    rows = [l.strip() for l in open(fn) if l.strip()]
    assert int(rows[0]) == N
    pieces, hints = [], []
    for i, l in enumerate(rows[1:]):
        c = l.split(",")
        e = [0 if int(x, 2) == 65535 else int(x, 2) for x in c[:4]]
        pieces.append(e)
        x, y, rot = int(c[4]), int(c[5]), int(c[6])
        if x or y or rot:
            hints.append((y, x, i))
    return pieces, hints


def main():
    pieces, hints = load(sys.argv[1])
    kinds = Counter(sum(1 for v in p if v == 0) for p in pieces)
    print("pieces by rim sides:", dict(kinds))
    frame_cols, int_cols = Counter(), Counter()
    inward = Counter()
    for p in pieces:
        z = [i for i, v in enumerate(p) if v == 0]
        if len(z) == 0:
            for v in p:
                int_cols[v] += 1
        elif len(z) == 1:
            i = z[0]
            int_cols[p[(i + 2) % 4]] += 1
            inward[p[(i + 2) % 4]] += 1
            frame_cols[p[(i + 1) % 4]] += 1
            frame_cols[p[(i + 3) % 4]] += 1
        else:
            for v in p:
                if v:
                    frame_cols[v] += 1
    print("frame colour half-edge counts:", sorted(frame_cols.values()))
    print("interior colour half-edge counts:", sorted(int_cols.values()))
    print("inward colours of the 56 edge pieces:", sorted(inward.items()))
    assert not (set(frame_cols) & set(int_cols))
    H = sum(int_cols.values())
    p_int = sum(v * v for v in int_cols.values()) / H ** 2
    print("H_int=%d p_int(sum f^2)=%.6f (1/17=%.6f)" % (H, p_int, 1 / 17))
    print("hints (row, col, piece):", hints)

    lpi = interior_match_logp(list(int_cols.values()), H // 2)
    lpf = frame_match_logp([v // 2 for v in frame_cols.values()], 60)
    print("log10 P_int(420)=%.3f  naive 420*log10(1/17)=%.3f" % (lpi[420], -420 * log10(17)))
    print("log10 P_frame(60)=%.3f naive=%.3f" % (lpf[60], -60 * log10(5)))
    print("per-edge cost in digits, interior, at e=1,100,200,300,400,420: ",
          ["%.3f" % (lpi[e - 1] - lpi[e]) for e in (1, 100, 200, 300, 400, 420)])

    def orders():
        yield "rows top-down", [(r, c) for r in range(N) for c in range(N)]
        yield "rows bottom-up", [(r, c) for r in reversed(range(N)) for c in range(N)]
        yield "cols left-right", [(r, c) for c in range(N) for r in range(N)]
        yield "cols right-left", [(r, c) for c in reversed(range(N)) for r in range(N)]

    centre = [h for h in hints if 5 <= h[0] <= 10 and 5 <= h[1] <= 10]
    assert len(centre) == 1
    variants = {
        "centre clue only": {(h[0], h[1]) for h in centre},
        "all five clues": {(h[0], h[1]) for h in hints},
    }
    results = {}
    for vname, fixed in variants.items():
        pools = {"corner": 4, "edge": 56, "interior": 196 - len(fixed)}
        print("\n== %s ==" % vname)
        for oname, order in orders():
            prof = profile(N, order, pools, lpi, lpf, fixed)
            logs = [x[0] for x in prof]
            peak = max(logs)
            d = logs.index(peak) + 1
            tot = logsum10(logs)
            print("%-16s log10 S=%.3f  peak log10 N=%.2f at depth %d (row %d)  "
                  "log10 sum_d N=%.2f  log10 N(128)=%.2f  first depth with N>1e18: %d"
                  % (oname, logs[-1], peak, d, (d - 1) // N, tot, logs[127],
                     next(i + 1 for i, x in enumerate(logs) if x > 18)))
            results[(vname, oname)] = prof
    # table of the bulge, all five clues, top-down
    prof = results[("all five clues", "rows top-down")]
    print("\nlog10 N after each full row, all five clues, rows top-down:")
    print(" ".join("%.1f" % prof[16 * r + 15][0] for r in range(N)))
    prof = results[("centre clue only", "rows top-down")]
    print("log10 N after each full row, centre clue only, rows top-down:")
    print(" ".join("%.1f" % prof[16 * r + 15][0] for r in range(N)))

    # seam MITM: lists generated by scan DFS, so each list costs the sum of
    # its own profile up to the seam (it cannot skip its own rising flank).
    print("\n== seam meet in the middle (tops = rows 0..r-1, bottoms = rows r..15) ==")
    for vname, fixed in variants.items():
        td = [x[0] for x in results[(vname, "rows top-down")]]
        bu = [x[0] for x in results[(vname, "rows bottom-up")]]
        dfs = min(logsum10([x[0] for x in results[(vname, o)]])
                  for o in ("rows top-down", "rows bottom-up", "cols left-right", "cols right-left"))
        for r in range(1, 16):
            t, b = td[16 * r - 1], bu[16 * (N - r) - 1]
            ct, cb = logsum10(td[:16 * r]), logsum10(bu[:16 * (N - r)])
            print("%-17s r=%2d  list sizes: tops %.1f bottoms %.1f | generation cost: %.1f + %.1f = %.2f"
                  " | DFS %.2f | gain %.2f digits | seam-matching pairs %.1f"
                  % (vname, r, t, b, ct, cb, logsum10([ct, cb]), dfs,
                     dfs - logsum10([ct, cb]), t + b - (td[-1] if False else 0) ))
    # quadrant lists
    print("\n== 8x8 corner quadrant lists ==")
    for vname, fixed in variants.items():
        pools = {"corner": 4, "edge": 56, "interior": 196 - len(fixed)}
        for name, rows, cols in (("top-left", range(8), range(8)), ("top-right", range(8), range(8, 16)),
                                 ("bottom-left", range(8, 16), range(8)), ("bottom-right", range(8, 16), range(8, 16))):
            order = [(r, c) for r in rows for c in cols]
            prof = profile(N, order, pools, lpi, lpf, fixed)
            print("%-17s %-12s log10 N(quadrant)=%.2f (peak along scan %.2f)" %
                  (vname, name, prof[-1][0], max(x[0] for x in prof)))
    from math import lgamma, log
    def lc(n, k):
        return (lgamma(n + 1) - lgamma(k + 1) - lgamma(n - k + 1)) / log(10)
    print("log10 P(two independent quadrant piece sets are disjoint) = %.2f"
          % ((lc(147, 49) - lc(196, 49)) + (lc(42, 14) - lc(56, 14)) + log10(3 / 4)))
    print("log10 P(two independent half-board piece sets are complementary) = %.2f"
          % (-(lc(196, 98) + lc(56, 28) + lc(4, 2))))
    print("log10 P(four independent quadrant sets partition the pieces) = %.2f"
          % ((lgamma(197) - 4 * lgamma(50)) / log(10) - 4 * lc(196, 49)
             + (lgamma(57) - 4 * lgamma(15)) / log(10) - 4 * lc(56, 14) + log10(24 / 256)))
    print("seam key space: full row seam 17^14*5^2 = 10^%.1f ; 8-edge quadrant seam 17^7*5 = 10^%.1f"
          % (14 * log10(17) + 2 * log10(5), 7 * log10(17) + log10(5)))
    print("clue arithmetic: early clue cuts the count by 4*pool: log10(4*191)=%.2f digits = %.1f bits"
          % (log10(4 * 191), log10(4 * 191) / log10(2)))

    # interior given the true frame: 14x14 block, every boundary edge already constrained
    print("\n== interior given the correct frame (frame cells pre-filled, not counted) ==")
    for vname, fixed in variants.items():
        frame_cells = [(r, c) for r in range(N) for c in range(N) if cell_kind(N, r, c) != "interior"]
        order = frame_cells + [(r, c) for r in range(1, N - 1) for c in range(1, N - 1)]
        pools = {"corner": 4, "edge": 56, "interior": 196 - len(fixed)}
        prof = profile(N, order, pools, lpi, lpf, fixed)
        base = prof[59][0]
        logs = [x[0] - base for x in prof[60:]]
        print("%-18s log10(#frames)=%.2f ; interior peak log10 N=%.2f at interior depth %d ; "
              "log10 sum=%.2f ; end=%.2f"
              % (vname, base, max(logs), logs.index(max(logs)) + 1, logsum10(logs), logs[-1]))

    # pool-restriction ledger: top half knows its exact piece set
    print("\n== partition ledger (all five clues): pools restricted to the true half ==")
    fixed = variants["all five clues"]
    top_fixed = {f for f in fixed if f[0] < 8}
    order = [(r, c) for r in range(8) for c in range(N)]
    full = profile(N, order, {"corner": 4, "edge": 56, "interior": 191}, lpi, lpf, fixed)
    n_int_top = 6 * 14 + 14 - len(top_fixed)  # rows 1..7 interior cells
    half = profile(N, order, {"corner": 2, "edge": 28, "interior": n_int_top}, lpi, lpf, fixed)
    print("top 8 rows, free pool : peak log10 N=%.2f, end log10 N=%.2f" %
          (max(x[0] for x in full), full[-1][0]))
    print("top 8 rows, exact pool: peak log10 N=%.2f, end log10 N=%.2f" %
          (max(x[0] for x in half), half[-1][0]))
    print("log10 number of top/bottom splits of the free pieces: interior %.2f, edge %.2f, corner %.2f"
          % (log10(comb(191, n_int_top)), log10(comb(56, 28)), log10(comb(4, 2))))
    print("checkerboard: log10 C(196,98)=%.2f" % log10(comb(196, 98)))
    # mean-field relaxation inflation r^r/r!
    for r in (16, 32, 48, 72, 150):
        print("relaxation that forgets distinctness on r=%d pieces inflates counts by 10^%.1f"
              % (r, r * log10(r) - log10_fact(r)))


main()
