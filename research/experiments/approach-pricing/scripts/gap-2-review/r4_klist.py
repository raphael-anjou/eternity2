def show(rect, ideal, depth=0, lim=3):
    c, how = plan(*rect, ideal); n = info(*rect)[0]
    print("     " + "  " * depth + "rows %d-%d cols %d-%d: list 2^%.1f, cost 2^%.1f by %s" % (rect[0], rect[1] - 1, rect[2], rect[3] - 1, n, c, how))
    if how == "scan" or depth >= lim: return
    k = int(how.split()[1].split("|")[0])
    if how.startswith("rows"): show((rect[0], rect[0] + k, rect[2], rect[3]), ideal, depth + 1, lim); show((rect[0] + k, rect[1], rect[2], rect[3]), ideal, depth + 1, lim)
    else: show((rect[0], rect[1], rect[2], rect[2] + k), ideal, depth + 1, lim); show((rect[0], rect[1], rect[2] + k, rect[3]), ideal, depth + 1, lim)
