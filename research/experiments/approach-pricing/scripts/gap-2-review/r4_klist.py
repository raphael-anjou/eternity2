@lru_cache(None)
def plan(r1, r2, c1, c2, ideal):
    """cheapest way to produce the list of a rectangle: (cost, description)"""
    n, w = info(r1, r2, c1, c2)
    best = (w, "scan")
    if (r2 - r1) * (c2 - c1) == 1: return best
    for cutr in range(r1 + 1, r2):
        a, b = (r1, cutr, c1, c2), (cutr, r2, c1, c2)
        ca, cb2 = plan(*a, ideal)[0], plan(*b, ideal)[0]
        if max(ca, cb2) >= best[0]: continue
        j = n if ideal else info(*a)[0] + info(*b)[0] - seam(a, b)
        c = max(ca, cb2, j, n)
        if c < best[0]: best = (c, "rows %d|%d" % (cutr - r1, r2 - cutr))
    for cutc in range(c1 + 1, c2):
        a, b = (r1, r2, c1, cutc), (r1, r2, cutc, c2)
        ca, cb2 = plan(*a, ideal)[0], plan(*b, ideal)[0]
        if max(ca, cb2) >= best[0]: continue
        j = n if ideal else info(*a)[0] + info(*b)[0] - seam(a, b)
        c = max(ca, cb2, j, n)
        if c < best[0]: best = (c, "cols %d|%d" % (cutc - c1, c2 - cutc))
    return best
for ideal in (False, True):
    res = []
