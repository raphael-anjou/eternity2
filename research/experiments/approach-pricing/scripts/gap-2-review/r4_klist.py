"""Review item 1: joins of more than two lists, priced with the real geometry (first-moment model, real census, five clues).
Lists are strict fillings of rectangles (full tile pool). A join of two adjacent rectangles a, b into a larger one:
  key = seam colours (hashable). Disjointness of the two used sets is NOT an equality unless a + b is the whole board,
  so a seam-keyed join produces N(a) N(b) / 2^F(a,b) candidates, of which N(a+b) survive the disjointness test.
Priced, all in widest-level terms (comparable to the memo's 2^128.7 and to the tree's widest level):
  A. the named 4-list plans (quadrants, bands) with Schroeppel-Shamir style modulus guessing;
  B. every guillotine plan (recursive splits into rectangles), leaves generated by row or column scan,
     with (i) seam-keyed joins as they exist and (ii) a hypothetical output-sensitive disjoint join (cost = output size)."""
