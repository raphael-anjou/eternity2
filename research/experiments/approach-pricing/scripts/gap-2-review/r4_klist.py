def cells(r1, r2, c1, c2): return [(r, c) for r in range(r1, r2) for c in range(c1, c2)]
def orders(r1, r2, c1, c2):
    cs = cells(r1, r2, c1, c2)
    return [cs, cs[::-1], sorted(cs, key=lambda x: (x[1], x[0])), sorted(cs, key=lambda x: (-x[1], x[0]))]
@lru_cache(None)
def info(r1, r2, c1, c2):
    """(log2 list size, best widest level over four scans)"""
    best = None; n = None
    for o in orders(r1, r2, c1, c2):
        l = levels(o); n = l[-1]; w = max(l)
        best = w if best is None else min(best, w)
    return n, best
def seam(a, b):
    """uniform seam width between two adjacent rectangles"""
    A_ = set(cells(*a)); bits = 0.0
    for (r, c) in cells(*b):
        for (rr, cc) in ((r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)):
            if (rr, cc) in A_:
                bits += log2(5) if ((r == rr and r in (0, N - 1)) or (c == cc and c in (0, N - 1))) else log2(17)
    return bits
